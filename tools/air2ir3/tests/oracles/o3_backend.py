#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""O3 backend oracle for air2ir3 compile (ir3, Adreno 619 / a6xx).

  o3_backend.py --compile AIR2IR3 --asm A2I-O3-ASM --out DIR

Generates MIT synthetic AIR fragment shaders from one template and checks:
  sensitivity  each semantic change (operand order, swizzle, immediate,
               constant-buffer offset) changes the encoded program
  stability    transformations without effect (dead code, double negation,
               identity swizzle) leave the encoded program byte-identical
  determinism  repeated compilation is byte-identical
  encoding     every binary decodes and re-assembles to the same words
               through Mesa's ir3 assembler (a2i-o3-asm); an invalid word is
               rejected (negative control)
  limits       binding limits are enforced before NIR (render target 8,
               buffer location 31) with no output files
Nothing is executed on a GPU. Exit 0 = all checks pass, 1 = failure.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS = os.path.dirname(HERE)
DL = ("e-p:64:64:64-i1:8:8-i8:8:8-i16:16:16-i32:32:32-i64:64:64-f32:32:32-f64:64:64-"
      "v16:16:16-v24:32:32-v32:32:32-v48:64:64-v64:64:64-v96:128:128-v128:128:128-"
      "v192:256:256-v256:256:256-v512:512:512-v1024:1024:1024-n8:16:32")

TEMPLATE = """; SPDX-License-Identifier: MIT
; generated by air2ir3 tests/oracles/o3_backend.py (variant {name})
source_filename = "o3"
target datalayout = "{dl}"
target triple = "air64-apple-ios18.0.0"

define <4 x float> @o3(<4 x float> %color, ptr addrspace(2) %cb) {{
  %k0.p = getelementptr inbounds <4 x float>, ptr addrspace(2) %cb, i64 {off}
  %k0 = load <4 x float>, ptr addrspace(2) %k0.p, align 16
  %k1.p = getelementptr inbounds <4 x float>, ptr addrspace(2) %cb, i64 1
  %k1 = load <4 x float>, ptr addrspace(2) %k1.p, align 16
  %m = fmul <4 x float> %color, %k0
  %s = fsub <4 x float> {sub}
  %t = fmul <4 x float> %s, <float {c}, float {c}, float {c}, float {c}>
{extra}  %o = shufflevector <4 x float> {res}, <4 x float> poison, <4 x i32> <{mask}>
  ret <4 x float> %o
}}

!air.fragment = !{{!0}}
!0 = !{{ptr @o3, !1, !3}}
!1 = !{{!2}}
!2 = !{{!"air.render_target", i32 {rt}, i32 0, !"air.arg_type_name", !"float4", !"air.arg_name", !"out"}}
!3 = !{{!4, !5}}
!4 = !{{i32 0, !"air.fragment_input", !"generated(5colorDv4_f)", !"air.center", !"air.perspective", !"air.arg_type_name", !"float4", !"air.arg_name", !"color"}}
!5 = !{{i32 1, !"air.buffer", !"air.location_index", i32 {loc}, i32 1, !"air.read", !"air.address_space", i32 2, !"air.arg_type_size", i32 16, !"air.arg_type_align_size", i32 16, !"air.arg_type_name", !"float4", !"air.arg_name", !"cb"}}
"""
MASK_ID = "i32 0, i32 1, i32 2, i32 3"
BASE = dict(off=0, sub="%m, %k1", c="2.000000e+00", extra="", res="%t", mask=MASK_ID, rt=0, loc=0)
SEMANTIC = {
    "swap_fsub_operands": dict(sub="%k1, %m"),
    "swizzle_yxzw": dict(mask="i32 1, i32 0, i32 2, i32 3"),
    "immediate_3_0": dict(c="3.000000e+00"),
    "cbuffer_offset_32": dict(off=2),
}
NOOP = {
    "dead_fadd": dict(extra="  %dead = fadd <4 x float> %t, %k1\n"),
    "double_fneg": dict(extra="  %n1 = fneg <4 x float> %t\n  %n2 = fneg <4 x float> %n1\n",
                        res="%n2"),
    "identity_swizzle": dict(extra="  %id = shufflevector <4 x float> %t, <4 x float> poison, "
                                   "<4 x i32> <" + MASK_ID + ">\n", res="%id"),
}
LIMITS = {"render_target_8": dict(rt=8), "buffer_location_31": dict(loc=31)}


class Run:
    def __init__(self, a):
        self.a, self.fails, self.passes = a, [], 0

    def check(self, name, cond, detail=""):
        if cond:
            self.passes += 1
            print("PASS", name)
        else:
            self.fails.append(name)
            print("FAIL %s: %s" % (name, detail))

    def build(self, name, **over):
        p = dict(BASE, **over)
        ll = os.path.join(self.a.out, name + ".ll")
        with open(ll, "w") as f:
            f.write(TEMPLATE.format(name=name, dl=DL, **p))
        bc = ll[:-3] + ".bc"
        subprocess.run([self.a.llvm_as, ll, "-o", bc], check=True)
        lib = ll[:-3] + ".metallib"
        subprocess.run([sys.executable, os.path.join(TESTS, "gen_metallib.py"), lib, "--bc", bc,
                        "--name", "o3", "--type", "1"], check=True)
        return lib

    def compile(self, name, lib):
        prefix = os.path.join(self.a.out, name)
        for ext in (".bin", ".dis", ".nir", ".json"):
            if os.path.exists(prefix + ext):
                os.remove(prefix + ext)
        p = subprocess.run([self.a.compile, "compile", lib, prefix], capture_output=True, text=True)
        if "Sanitizer" in p.stderr or "runtime error" in p.stderr:
            self.check(name + ".sanitizers", False, p.stderr[:300])
        return p, prefix


def insns(path):
    out = []
    for line in open(path):
        s = line.strip()
        if s and s != "nop":
            out.append(s)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--compile", required=True)
    ap.add_argument("--asm", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--llvm-as", default="llvm-as-18")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    r = Run(a)
    res = {}

    def compiled(name, **over):
        p, prefix = r.compile(name, r.build(name, **over))
        r.check(name + ".compile", p.returncode == 0, p.stderr.strip()[:300])
        if p.returncode:
            return None
        b = open(prefix + ".bin", "rb").read()
        j = json.load(open(prefix + ".json"))
        res[name] = {"sha256": hashlib.sha256(b).hexdigest(), "insns": insns(prefix + ".dis"),
                     "instrs_count": j["ir3"]["instrs_count"], "max_reg": j["ir3"]["max_reg"],
                     "constlen": j["ir3"]["constlen"]}
        q = subprocess.run([a.asm, prefix + ".bin"], capture_output=True, text=True)
        r.check(name + ".asm_roundtrip", q.returncode == 0, q.stdout[:300] + q.stderr[:200])
        return res[name]

    base = compiled("base")
    if base is None:
        print("o3: base variant failed to compile")
        return 1
    r.check("base.json_gpu_executed_false",
            json.load(open(os.path.join(a.out, "base.json")))["gpu_executed"] is False)
    for k in (1, 2):
        again = compiled("base_again%d" % k)
        r.check("determinism.run%d" % k, again and again["sha256"] == base["sha256"],
                "recompiled binary differs")
    for name, over in SEMANTIC.items():
        v = compiled("sem_" + name, **over)
        r.check("sensitivity." + name, v and v["sha256"] != base["sha256"] and
                v["insns"] != base["insns"], "semantic change did not change the program")
    for name, over in NOOP.items():
        v = compiled("noop_" + name, **over)
        r.check("stability." + name, v and v["sha256"] == base["sha256"],
                "no-op transformation changed the program: %s" % (v and v["insns"]))
    for name, over in LIMITS.items():
        p, prefix = r.compile("lim_" + name, r.build("lim_" + name, **over))
        r.check("limit." + name, p.returncode == 7 and
                p.stderr.startswith("E_UNSUPPORTED_BINDING:") and
                not any(os.path.exists(prefix + e) for e in (".bin", ".dis", ".nir", ".json")),
                "rc=%d %s" % (p.returncode, p.stderr.strip()[:200]))
    bad = os.path.join(a.out, "invalid_word.bin")
    with open(bad, "wb") as f:
        f.write(b"\xff" * 8 + b"\x00" * 8)
    q = subprocess.run([a.asm, bad], capture_output=True, text=True)
    r.check("encoding.negative_control_invalid_word", q.returncode == 1, q.stdout[:200])

    with open(os.path.join(a.out, "o3-report.json"), "w") as f:
        json.dump({"variants": res, "passed": r.passes, "failed": r.fails}, f, indent=1)
    print("o3: %d passed, %d failed (%s)" % (r.passes, len(r.fails), a.out))
    return 0 if not r.fails else 1


if __name__ == "__main__":
    sys.exit(main())
